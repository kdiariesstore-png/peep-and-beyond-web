import math
from dsl import *

C_ = "Nature & Weather"


def ring(cx, cy, dist, n, fn, offset=0):
    out = []
    for i in range(n):
        a = 360 * i / n + offset
        r = math.radians(a)
        out.append(fn(cx + dist * math.cos(r), cy + dist * math.sin(r), a))
    return out


